import {readFile,writeFile,rm,cp} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {createRequire} from 'node:module';
const root=path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const {validate}=createRequire(import.meta.url)('./validate-data.cjs');
const data=validate(JSON.parse(await readFile(path.join(root,'data/venues.json'),'utf8')));
const generated=`/* Generated by npm run build from data/venues.json. Edit the JSON source. */\n(function(root){const data=${JSON.stringify(data)};if(typeof module!=='undefined')module.exports=data;else root.CAFE_DATA=data;})(typeof window!=='undefined'?window:globalThis);\n`;
await writeFile(path.join(root,'public/data.js'),generated);
await rm(path.join(root,'dist'),{force:true,recursive:true});
await cp(path.join(root,'public'),path.join(root,'dist'),{recursive:true});
console.log(`Build complete: dist/ (${data.places.length} venues)`);
